<?php

$n1 = 104;
$n2 = 16;
$operacao = "*";

if ($operacao == "+") {
  echo "A soma é: " , $n1 + $n2;
}
elseif ($operacao == "*"){
  echo "A multiplcação é: " , $n1 * $n2;
}
elseif ($operacao == "-"){
  echo "A subtração é: " , $n1 - $n2;
}
elseif ($operacao == "/"){
  echo "A divisão é: " , $n1 / $n2;
}

?>